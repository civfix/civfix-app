#!/usr/bin/env node
/**
 * Generates `src/i18n/resources.ts` from one static import per locale and namespace JSON: Metro cannot
 * statically resolve a dynamic `require` or `import()`. A namespace missing for one locale is skipped
 * there, and i18next falls back to `en`.
 */
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const i18nDir = join(__dirname, "..", "src", "i18n")
const localesDir = join(i18nDir, "locales")
const outFile = join(i18nDir, "resources.ts")

const LOCALES = ["en", "es", "de", "ko"]

// Sorted for stable output.
const namespaces = readdirSync(join(localesDir, "en"))
  .filter((f) => f.endsWith(".json"))
  .map((f) => f.replace(/\.json$/, ""))
  .sort()

function ident(lng, ns) {
  return `${lng}_${ns}`.replace(/[^A-Za-z0-9_]/g, "_")
}

function namespacesFor(lng) {
  const present = new Set(
    readdirSync(join(localesDir, lng))
      .filter((f) => f.endsWith(".json"))
      .map((f) => f.replace(/\.json$/, "")),
  )
  return namespaces.filter((ns) => present.has(ns))
}

const importLines = []
const resourceEntries = []

for (const lng of LOCALES) {
  const nsList = namespacesFor(lng)
  for (const ns of nsList) {
    importLines.push(`import ${ident(lng, ns)} from "./locales/${lng}/${ns}.json"`)
  }
  const nsEntries = nsList.map((ns) => `    "${ns}": ${ident(lng, ns)},`).join("\n")
  resourceEntries.push(`  ${lng}: {\n${nsEntries}\n  },`)
}

const nsLiteral = namespaces.map((ns) => `  "${ns}",`).join("\n")

const banner = `/**
 * AUTO-GENERATED by scripts/gen-i18n-resources.mjs: DO NOT EDIT BY HAND.
 *
 * Re-run \`node scripts/gen-i18n-resources.mjs\` after adding/removing a namespace or locale. It scans
 * src/i18n/locales/<lng>/<ns>.json and emits static imports (Metro-safe; no dynamic require) assembled
 * into the i18next \`resources\` object + the \`namespaces\` list config.ts feeds to \`ns\`.
 */`

const body = `${banner}
import type { Resource } from "i18next"

${importLines.join("\n")}

/** Every namespace (catalog file) the app loads. \`config.ts\` passes this to i18next's \`ns\`. */
export const namespaces = [
${nsLiteral}
] as const

/** The assembled i18next resources: locale -> namespace -> catalog object. */
export const resources: Resource = {
${resourceEntries.join("\n")}
}
`

writeFileSync(outFile, body)
console.log(
  `Wrote ${outFile}\n  locales: ${LOCALES.join(", ")}\n  namespaces: ${namespaces.length}\n  imports: ${importLines.length}`,
)
