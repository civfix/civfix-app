// Writes dist/theme.css, the Tailwind 4 `@theme` block the website builds on, from the token values tsup
// just built, so the CSS can never drift from the JS export. It maps exactly the scales the website's
// utilities name; the scheme colours stay CSS variables in the app, because they switch with dark mode.
import { writeFileSync } from "node:fs"
import { URL } from "node:url"
import { tokens } from "../dist/index.js"

const { color, fontSize, lineHeight, motion, radius, shadow, space, tracking } = tokens

const px = (n) => `${n}px`

// `pin` is a four-corner shorthand for the map pin's CSS shape, not a utility radius.
const RADII = ["xs", "sm", "md", "lg", "xl", "2xl", "pill"]

const theme = [
  ...RADII.map((k) => [`--radius-${k}`, px(radius[k])]),
  ["--shadow-s1", shadow.s1],
  ["--shadow-s2", shadow.s2],
  ["--shadow-s3", shadow.s3],
  ["--shadow-s4", shadow.s4],
  ["--shadow-pin", shadow.pin],
  ["--shadow-sheen", shadow.sheenTop],
  ["--shadow-ring", shadow.ring],
  ...Object.entries(space).map(([k, v]) => [`--spacing-token-${k}`, px(v)]),
  ...Object.entries(fontSize).map(([k, v]) => [`--text-token-${k}`, v]),
  ...Object.entries(lineHeight).map(([k, v]) => [`--leading-${k}`, String(v)]),
  ["--tracking-tightest", tracking.tight],
  ["--tracking-snugger", tracking.snug],
  ["--tracking-wider", tracking.wide],
  ["--ease-out", motion.ease.out],
  ["--ease-spring", motion.ease.spring],
  ["--ease-in-out", motion.ease.inOut],
  ...Object.entries(color.brand).map(([k, v]) => [`--color-brand-${k}`, v]),
]

const css = [
  "/* Generated by scripts/build-theme.mjs from the @civfix/tokens values; do not edit. */",
  "@theme {",
  ...theme.map(([name, value]) => `  ${name}: ${value};`),
  "}",
  "",
].join("\n")

writeFileSync(new URL("../dist/theme.css", import.meta.url), css)
