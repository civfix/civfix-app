import { execFileSync } from "node:child_process"
import { readdirSync, readFileSync } from "node:fs"
import { createRequire } from "node:module"
import { fileURLToPath } from "node:url"
import { describe, expect, it } from "vitest"
import { tokens } from "../src/design-tokens.js"

const PACKAGE_DIR = fileURLToPath(new URL("..", import.meta.url))
const CHANGESET_DIR = fileURLToPath(new URL("../../../.changeset", import.meta.url))

/** The built export, resolved through the package's own `exports` as the website imports it. */
function themeCss(): string {
  let path: string | undefined
  try {
    path = createRequire(import.meta.url).resolve("@civfix/tokens/theme.css")
  } catch {
    path = undefined
  }
  expect(path, "@civfix/tokens/theme.css").toBeDefined()
  return path === undefined ? "" : readFileSync(path, "utf8")
}

/** The variables of the file's single `@theme` block. */
function themeVars(): Map<string, string> {
  const blocks = [...themeCss().matchAll(/@theme\s*\{([^}]*)\}/g)]
  expect(blocks, "@theme blocks").toHaveLength(1)
  const body = blocks[0]?.[1] ?? ""
  return new Map(
    [...body.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map((m) => [m[1] ?? "", (m[2] ?? "").trim()]),
  )
}

/** Fails naming the variable, so a drifted token points straight at its CSS line. */
function expectVars(expected: ReadonlyArray<readonly [string, string]>): void {
  const vars = themeVars()
  for (const [name, value] of expected) expect(vars.get(name), name).toBe(value)
}

const px = (n: number): string => `${String(n)}px`

const RADII = ["xs", "sm", "md", "lg", "xl", "2xl", "pill"] as const

const RADIUS_VARS = RADII.map((k) => [`--radius-${k}`, px(tokens.radius[k])] as const)

const SHADOW_VARS = [
  ["--shadow-s1", tokens.shadow.s1],
  ["--shadow-s2", tokens.shadow.s2],
  ["--shadow-s3", tokens.shadow.s3],
  ["--shadow-s4", tokens.shadow.s4],
  ["--shadow-pin", tokens.shadow.pin],
  ["--shadow-sheen", tokens.shadow.sheenTop],
  ["--shadow-ring", tokens.shadow.ring],
] as const

const SCALE_VARS = [
  ...Object.entries(tokens.space).map(([k, v]) => [`--spacing-token-${k}`, px(v)] as const),
  ...Object.entries(tokens.fontSize).map(([k, v]) => [`--text-token-${k}`, v] as const),
  ["--leading-tight", String(tokens.lineHeight.tight)],
  ["--leading-snug", String(tokens.lineHeight.snug)],
  ["--leading-base", String(tokens.lineHeight.base)],
  ["--leading-loose", String(tokens.lineHeight.loose)],
  ["--tracking-tightest", tokens.tracking.tight],
  ["--tracking-snugger", tokens.tracking.snug],
  ["--tracking-wider", tokens.tracking.wide],
  ["--ease-out", tokens.motion.ease.out],
  ["--ease-spring", tokens.motion.ease.spring],
  ["--ease-in-out", tokens.motion.ease.inOut],
  ...Object.entries(tokens.color.brand).map(([k, v]) => [`--color-brand-${k}`, v] as const),
] as const

describe("@civfix/tokens/theme.css", () => {
  it("T1: holds one @theme block with the token radii and no pin radius", () => {
    expect(RADIUS_VARS.map(([, value]) => value)).toEqual([
      "6px",
      "10px",
      "14px",
      "20px",
      "28px",
      "36px",
      "999px",
    ])
    expectVars(RADIUS_VARS)
    expect(themeVars().has("--radius-pin")).toBe(false)
  })

  it("T2: holds the token shadows exactly", () => {
    expectVars(SHADOW_VARS)
  })

  it("T3: holds the spacing, type, line-height, tracking, easing and brand scales", () => {
    expect(Object.keys(tokens.space)).toHaveLength(10)
    expect(Object.keys(tokens.fontSize)).toHaveLength(12)
    expectVars(SCALE_VARS)
  })

  it("T4: is compared against the tokens object, so a drifted value fails on its variable", () => {
    const vars = themeVars()
    const drifted = [...RADIUS_VARS, ...SHADOW_VARS, ...SCALE_VARS].filter(
      ([name, value]) => vars.get(name) !== value,
    )
    expect(drifted.map(([name]) => name)).toEqual([])
  })

  it("maps nothing beyond those scales", () => {
    expect([...themeVars().keys()].sort()).toEqual(
      [...RADIUS_VARS, ...SHADOW_VARS, ...SCALE_VARS].map(([name]) => name).sort(),
    )
  })
})

describe("the theme export's packaging", () => {
  const pkg: unknown = JSON.parse(readFileSync(`${PACKAGE_DIR}/package.json`, "utf8"))
  const field = (key: string): unknown =>
    typeof pkg === "object" && pkg !== null && key in pkg
      ? (pkg as Record<string, unknown>)[key]
      : undefined
  const entry = (key: string, sub: string): unknown => {
    const value = field(key)
    return typeof value === "object" && value !== null && sub in value
      ? (value as Record<string, unknown>)[sub]
      : undefined
  }

  it("T5: is exported, generated by the build after tsup, untracked and unpublished", () => {
    expect(entry("exports", "./theme.css")).toBe("./dist/theme.css")
    const build = entry("scripts", "build")
    expect(
      typeof build === "string" ? build.split("&&").map((step) => step.trim()) : build,
    ).toEqual(["tsup", "node scripts/build-theme.mjs"])
    const tracked = execFileSync("git", ["ls-files", "dist"], {
      cwd: PACKAGE_DIR,
      encoding: "utf8",
    })
    expect(tracked.trim()).toBe("")
    expect(field("version")).toBe("0.1.1")
    const naming = readdirSync(CHANGESET_DIR)
      .filter((name) => name.endsWith(".md") && name !== "README.md")
      .filter((name) => readFileSync(`${CHANGESET_DIR}/${name}`, "utf8").includes("@civfix/tokens"))
    expect(naming).toEqual([])
  })
})
